# 1 to 100 
print("******1 to 100******\n")
for i in range(1,101):
    print(i,end=" ")

#100 to 1
print("\n******100 to 1******")
for x in range(100,0,-1):
    print(x,end=" ")
    
#odd number
print("\n******1 to 99******")
for a in range(1,101,2):
    print(a,end=" ")

#even number
print("\n******2 to 100******")
for b in range(0,101,2):
    print(b,end=" ")