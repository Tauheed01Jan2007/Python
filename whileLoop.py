# 1 to 100
print("\n******1 to 100******\n")
i=1
while i<=100:
    print(i,end=" ")
    i=i+1

print("\n******100 to 1******\n")
i=100
while i>=1:
    print(i,end=" ")
    i=i-1

# even number
print("\n******100 to 2******\n")
i=100
while i>=1:
    print(i,end=" ")
    i=i-2

print("\n******2 to 100******\n")
i=0
while i<101:
    print(i,end=" ")
    i=i+2
